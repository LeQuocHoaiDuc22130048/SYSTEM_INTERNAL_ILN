"""Generate granular permission migration and client mappings from the action catalog."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
actions = json.loads((ROOT / 'scripts/permission-actions.json').read_text(encoding='utf-8'))
retired = ['REPAIR_MANAGE', 'CUSTOMER_MANAGE', 'WAREHOUSE_MANAGE', 'WAREHOUSE_DELETE',
           'ATTENDANCE_MANAGE', 'EMPLOYEE_MANAGE', 'EMPLOYEE_SECURITY_MANAGE', 'DEVICE_MANAGE',
           'BANNER_MANAGE', 'APP_UPDATE_MANAGE', 'PERMISSION_MANAGE']
legacy_dart = {
    'REPAIR_MANAGE': 'manageRepairOrders', 'CUSTOMER_MANAGE': 'manageCustomers',
    'WAREHOUSE_MANAGE': 'manageWarehouse', 'WAREHOUSE_DELETE': 'deleteWarehouse',
    'ATTENDANCE_MANAGE': 'manageAttendance', 'EMPLOYEE_MANAGE': 'manageEmployees',
    'EMPLOYEE_SECURITY_MANAGE': 'manageEmployeeSecurity', 'DEVICE_MANAGE': 'manageDevices',
    'BANNER_MANAGE': 'manageBanners', 'APP_UPDATE_MANAGE': 'manageAppUpdates',
    'PERMISSION_MANAGE': 'managePermissions', 'REPAIR_STATUS_UPDATE': 'updateRepairOrderStatus',
    'REPAIR_ASSIGN': 'assignRepairOrders', 'REPAIR_VIEW': 'viewRepairOrders',
    'CUSTOMER_VIEW': 'viewCustomers', 'WAREHOUSE_VIEW': 'viewWarehouse',
    'ATTENDANCE_VIEW': 'viewAttendance', 'DEVICE_VIEW': 'viewDevices',
    'MESSAGING_USE': 'useMessages', 'NOTIFICATION_VIEW': 'viewNotifications',
}

def sql_string(value):
    return "'" + value.replace("'", "''") + "'"

rows = ',\n'.join('(' + ', '.join(map(sql_string, row[:4])) + ')' for row in actions)
sql = '''-- Generated by scripts/sync-permission-catalog.py. Do not edit applied migrations.
ALTER TABLE permissions ADD COLUMN assignable BOOLEAN NOT NULL DEFAULT TRUE;
CREATE TEMP TABLE granular_permission_mapping (
    code VARCHAR(80), parent_code VARCHAR(80), module VARCHAR(50), name VARCHAR(100)
) ON COMMIT DROP;
INSERT INTO granular_permission_mapping VALUES
''' + rows + ''';
INSERT INTO permissions(code, module, name, description)
SELECT code, module, name, name FROM granular_permission_mapping
ON CONFLICT (code) DO NOTHING;

INSERT INTO role_permissions(role_id, permission_id)
SELECT rp.role_id, child.id FROM granular_permission_mapping m
JOIN permissions parent ON parent.code = m.parent_code
JOIN role_permissions rp ON rp.permission_id = parent.id
JOIN permissions child ON child.code = m.code
ON CONFLICT DO NOTHING;

INSERT INTO user_permissions(user_id, permission_id, granted, granted_by, granted_at)
SELECT up.user_id, child.id, up.granted, up.granted_by, up.granted_at
FROM granular_permission_mapping m
JOIN permissions parent ON parent.code = m.parent_code
JOIN user_permissions up ON up.permission_id = parent.id
JOIN permissions child ON child.code = m.code
ON CONFLICT DO NOTHING;

INSERT INTO role_permissions(role_id, permission_id)
SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
WHERE p.code = 'ATTENDANCE_KIOSK_USE' AND r.code IN ('SUPER_ADMIN','ADMIN','MANAGER','TECHNICIAN','ATTENDANCE')
ON CONFLICT DO NOTHING;
INSERT INTO user_permissions(user_id, permission_id, granted)
SELECT u.id, p.id, TRUE FROM users u CROSS JOIN permissions p
WHERE LOWER(u.username) = 'attendance' AND p.code = 'ATTENDANCE_KIOSK_USE'
ON CONFLICT DO NOTHING;

UPDATE permissions SET assignable = FALSE WHERE code IN (''' + ','.join(map(sql_string, retired)) + ''');
'''
(ROOT / 'backend/src/main/resources/db/migration/V70__granular_action_permissions.sql').write_text(sql, encoding='utf-8')

groups = {}
for code, parent, _, label, dart in actions:
    groups.setdefault(parent, []).append((code, dart))
web = '// Generated by scripts/sync-permission-catalog.py.\n'
web += 'export const ACTION_PERMISSION_LABELS: Record<string, string> = ' + json.dumps({r[0]: r[3] for r in actions}, ensure_ascii=False, indent=2) + ';\n'
web += 'export const LEGACY_PERMISSION_ALIASES: Record<string, string[]> = ' + json.dumps({p: [c for c, _ in groups[p]] for p in retired}, indent=2) + ';\n'
web += 'export const ROLE_PERMISSION_EXPANSION: Record<string, string[]> = ' + json.dumps({p: [c for c, _ in values] for p, values in groups.items() if p != 'KIOSK'}, indent=2) + ';\n'
(ROOT / 'frontend/src/utils/actionPermissions.ts').write_text(web, encoding='utf-8')

path = ROOT / 'app_native/lib/models/app_permission.dart'
dart = path.read_text(encoding='utf-8')
missing = [r for r in actions if f'  {r[4]},' not in dart]
dart = dart.replace('enum AppPermission {', 'enum AppPermission {\n' + ''.join(f'  {r[4]},\n' for r in missing))
cases = ''.join(f"      case AppPermission.{r[4]}:\n        return '{r[0]}';\n" for r in missing)
dart = dart.replace('    switch (this) {', '    switch (this) {\n' + cases, 1)
marker = '// Generated permission expansion.'
dart = dart.split(marker)[0].rstrip() + '\n\n' + marker + '\n'
for name, parents in [('legacyPermissionAliases', retired), ('rolePermissionExpansion', [p for p in groups if p != 'KIOSK'])]:
    dart += f'const {name} = <AppPermission, List<AppPermission>>{{\n'
    for parent in parents:
        dart += '  AppPermission.' + legacy_dart[parent] + ': [' + ', '.join('AppPermission.' + d for _, d in groups[parent]) + '],\n'
    dart += '};\n'
path.write_text(dart, encoding='utf-8')
print(f'Generated {len(actions)} granular actions; retired {len(retired)} grouped permissions.')
